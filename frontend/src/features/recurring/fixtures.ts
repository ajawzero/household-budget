/**
 * The All view with format 1.4 keep and tag: a kept, tagged stream (it keeps its open
 * cost cutting flag), tagged music lessons and the kept card fee with its review date.
 * Kids has no untagged bill left, so the server sends only its Hobbies section.
 */
export const TAGGED: RecurringResponse = (() => {
  const out = structuredClone(ALL);
  const by = new Map(out.items.map((i) => [i.key, i]));
  Object.assign(by.get("stream")!, { tag: "streaming", section_key: "lifestyle.streaming", keep: true });
  Object.assign(by.get("lessons")!, { tag: "hobbies", section_key: "kids.hobbies" });
  Object.assign(by.get("fee")!, { keep: true });
  out.sections = out.sections!.flatMap((s) => {
    if (s.key === "lifestyle") return [s, { key: "lifestyle.streaming", label: "Streaming", kind: "tag" as const, group_key: "lifestyle", group_label: "Lifestyle" }];
    if (s.key === "kids") return [{ key: "kids.hobbies", label: "Hobbies", kind: "tag" as const, group_key: "kids", group_label: "Kids and education" }];
    return [s];
  });
  return out;
})();
