#!/usr/bin/env bash
# Generates frontend/src/lib/api/schema.ts from the backend's OpenAPI schema.
#   scripts/gen_api_types.sh              # asks the backend (cli openapi)
#   scripts/gen_api_types.sh --from FILE  # uses a saved openapi.json
#   scripts/gen_api_types.sh --out FILE   # writes somewhere else (check.sh)
# openapi-typescript needs the TypeScript 5 API, and the app is on TypeScript
# 7, so the generator has its own small package in frontend/tools/apigen.
set -euo pipefail
# Never re-lock: use backend/uv.lock exactly as committed. A machine-level uv
# config (for example a package proxy) must not rewrite the lock file.
export UV_FROZEN=1

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export PATH="/opt/homebrew/opt/node@24/bin:$PATH"
TOOL="$ROOT/frontend/tools/apigen"
OUT="$ROOT/frontend/src/lib/api/schema.ts"
FROM=""
USAGE="Usage: $0 [--from openapi.json] [--out schema.ts]"

while [ $# -gt 0 ]; do
  case "$1" in
    --from) FROM="${2:?$USAGE}"; shift 2 ;;
    --out) OUT="${2:?$USAGE}"; shift 2 ;;
    *) echo "$USAGE" >&2; exit 2 ;;
  esac
done

if [ ! -x "$TOOL/node_modules/.bin/openapi-typescript" ]; then
  (cd "$TOOL" && npm ci --no-audit --no-fund)
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

if [ -n "$FROM" ]; then
  cp "$FROM" "$tmp/openapi.json"
else
  (cd "$ROOT/backend" && uv run python -m app.cli openapi --out "$tmp/openapi.json")
fi

"$TOOL/node_modules/.bin/openapi-typescript" "$tmp/openapi.json" -o "$tmp/schema.ts"
{
  echo "// Generated by scripts/gen_api_types.sh from the backend's OpenAPI. Do not edit."
  cat "$tmp/schema.ts"
} > "$OUT"
echo "Wrote $OUT"
